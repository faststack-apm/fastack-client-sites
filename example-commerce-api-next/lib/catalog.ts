import { readFileSync } from 'node:fs';
import { join } from 'node:path';

export interface Color { name: string; hex: string }
export interface Rule { scope?: string; isNew?: boolean; onSale?: boolean; doorbuster?: boolean; maxPrice?: number; brand?: string }
export interface CategoryRow {
  slug: string; name: string; parentSlug: string | null; type: 'category' | 'smart'; depth: number;
  sortOrder: number; description: string; productCount: number; rule: Rule | null;
}
export interface ProductRow {
  id: number; sku: string; slug: string; name: string; brand: string; categorySlug: string; categoryPath: string[];
  kind: string; imageKey: string; description: string; material: string; price: number; compareAtPrice: number | null;
  onSale: boolean; isNew: boolean; doorbuster: boolean; colors: Color[]; sizes: string[]; stock: number;
  rating: number; reviewCount: number; createdAt: string;
}
export interface StoreSettings {
  name: string; currency: string; freeShippingThreshold: number; flatShipping: number; taxRate: number;
}
export interface CatalogFile {
  store: StoreSettings;
  home: { sections: { title: string; collection: string }[] } & Record<string, unknown>;
  menu: unknown[];
  categories: CategoryRow[];
  products: ProductRow[];
}

const globalForCatalog = globalThis as unknown as { __catalog?: CatalogFile };

/** catalog.json is generated by tools/catalog-generator and shared with the Java API. */
export function catalog(): CatalogFile {
  if (!globalForCatalog.__catalog) {
    const file = join(process.cwd(), 'data', 'catalog.json');
    globalForCatalog.__catalog = JSON.parse(readFileSync(file, 'utf8')) as CatalogFile;
  }
  return globalForCatalog.__catalog;
}

export const settings = (): StoreSettings => catalog().store;
