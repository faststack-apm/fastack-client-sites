-- Vegas Clubwear commerce schema (PostgreSQL / H2 compatible)
CREATE TABLE IF NOT EXISTS categories (
    slug            VARCHAR(100) PRIMARY KEY,
    name            VARCHAR(200) NOT NULL,
    parent_slug     VARCHAR(100),
    type            VARCHAR(20)  NOT NULL,
    depth           INT          NOT NULL,
    sort_order      INT          NOT NULL,
    description     VARCHAR(1000),
    product_count   INT          NOT NULL DEFAULT 0,
    rule_scope      VARCHAR(100),
    rule_is_new     BOOLEAN,
    rule_on_sale    BOOLEAN,
    rule_doorbuster BOOLEAN,
    rule_max_price  NUMERIC(10, 2),
    rule_brand      VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS products (
    id               BIGINT PRIMARY KEY,
    sku              VARCHAR(40)    NOT NULL UNIQUE,
    slug             VARCHAR(200)   NOT NULL UNIQUE,
    name             VARCHAR(200)   NOT NULL,
    brand            VARCHAR(100)   NOT NULL,
    category_slug    VARCHAR(100)   NOT NULL,
    kind             VARCHAR(40)    NOT NULL,
    image_key        VARCHAR(40)    NOT NULL,
    description      VARCHAR(4000),
    material         VARCHAR(200),
    price            NUMERIC(10, 2) NOT NULL,
    compare_at_price NUMERIC(10, 2),
    on_sale          BOOLEAN        NOT NULL,
    is_new           BOOLEAN        NOT NULL,
    doorbuster       BOOLEAN        NOT NULL,
    stock            INT            NOT NULL,
    rating           DOUBLE PRECISION NOT NULL,
    review_count     INT            NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_products_price ON products (price);
CREATE INDEX IF NOT EXISTS idx_products_brand ON products (brand);

CREATE TABLE IF NOT EXISTS product_categories (
    product_id    BIGINT       NOT NULL REFERENCES products (id),
    position      INT          NOT NULL,
    category_slug VARCHAR(100) NOT NULL,
    PRIMARY KEY (product_id, position)
);
CREATE INDEX IF NOT EXISTS idx_product_categories_slug ON product_categories (category_slug, product_id);

CREATE TABLE IF NOT EXISTS product_colors (
    product_id BIGINT       NOT NULL REFERENCES products (id),
    position   INT          NOT NULL,
    name       VARCHAR(50)  NOT NULL,
    hex        VARCHAR(10)  NOT NULL,
    PRIMARY KEY (product_id, position)
);
CREATE INDEX IF NOT EXISTS idx_product_colors_name ON product_colors (name, product_id);

CREATE TABLE IF NOT EXISTS product_sizes (
    product_id BIGINT      NOT NULL REFERENCES products (id),
    position   INT         NOT NULL,
    size       VARCHAR(20) NOT NULL,
    PRIMARY KEY (product_id, position)
);
CREATE INDEX IF NOT EXISTS idx_product_sizes_size ON product_sizes (size, product_id);

CREATE TABLE IF NOT EXISTS carts (
    id         VARCHAR(36) PRIMARY KEY,
    status     VARCHAR(20) NOT NULL,
    promo_code VARCHAR(40),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id    VARCHAR(36) NOT NULL REFERENCES carts (id),
    product_id BIGINT      NOT NULL REFERENCES products (id),
    color      VARCHAR(50) NOT NULL,
    size       VARCHAR(20) NOT NULL,
    quantity   INT         NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_cart_items_cart ON cart_items (cart_id);

CREATE TABLE IF NOT EXISTS orders (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number    VARCHAR(20)    NOT NULL UNIQUE,
    cart_id         VARCHAR(36)    NOT NULL,
    status          VARCHAR(20)    NOT NULL,
    email           VARCHAR(200)   NOT NULL,
    first_name      VARCHAR(100)   NOT NULL,
    last_name       VARCHAR(100)   NOT NULL,
    address1        VARCHAR(200)   NOT NULL,
    address2        VARCHAR(200),
    city            VARCHAR(100)   NOT NULL,
    state           VARCHAR(50)    NOT NULL,
    postal_code     VARCHAR(20)    NOT NULL,
    country         VARCHAR(2)     NOT NULL,
    phone           VARCHAR(40),
    shipping_method VARCHAR(20)    NOT NULL,
    promo_code      VARCHAR(40),
    subtotal        NUMERIC(10, 2) NOT NULL,
    discount        NUMERIC(10, 2) NOT NULL,
    shipping        NUMERIC(10, 2) NOT NULL,
    tax             NUMERIC(10, 2) NOT NULL,
    total           NUMERIC(10, 2) NOT NULL,
    card_brand      VARCHAR(20)    NOT NULL,
    card_last4      VARCHAR(4)     NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS order_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT         NOT NULL REFERENCES orders (id),
    product_id BIGINT         NOT NULL,
    sku        VARCHAR(40)    NOT NULL,
    slug       VARCHAR(200)   NOT NULL,
    name       VARCHAR(200)   NOT NULL,
    image_key  VARCHAR(40)    NOT NULL,
    color      VARCHAR(50)    NOT NULL,
    size       VARCHAR(20)    NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    quantity   INT            NOT NULL,
    line_total NUMERIC(10, 2) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_order_items_order ON order_items (order_id);
